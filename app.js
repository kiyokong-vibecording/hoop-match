function isFreshListing(listing) {
  if (!listing.createdAt) return false;
  const createdAt = new Date(listing.createdAt);
  if (Number.isNaN(createdAt.getTime())) return false;
  return Date.now() - createdAt.getTime() <= 7 * 24 * 60 * 60 * 1000;
}

function getFilteredListings() {
  const {
    type,
    category,
    level,
    keyword,
    prefecture,
    municipality,
    courtOnly,
    activeOnly,
    dateRange,
    weekday,
    sort,
  } = activeListingFilters;
  const today = getToday();
  const lastDate =
    dateRange === "all"
      ? null
      : new Date(today.getTime() + Number(dateRange) * 24 * 60 * 60 * 1000);
  const normalizedKeyword = keyword.trim().toLowerCase();

  const filtered = state.listings.filter((listing) => {
    const listingDate = parseLocalDate(listing.date);
    const haystack = [
      listing.title,
      listing.prefecture,
      listing.municipality,
      listing.category,
      listing.level,
      listing.fee,
      listing.notes,
      typeLabels[listing.type],
    ]
      .join(" ")
      .toLowerCase();
    const matchesType =
      type === "all" ||
      listing.type === type ||
      (type === "pickup-helper" && ["pickup", "helper"].includes(listing.type));
    const matchesCategory = category === "all" || listing.category === category;
    const matchesLevel = level === "all" || listing.level === level;
    const matchesKeyword = !normalizedKeyword || haystack.includes(normalizedKeyword);
    const matchesPrefecture = prefecture === "all" || listing.prefecture === prefecture;
    const matchesMunicipality =
      municipality === "all" || listing.municipality === municipality;
    const matchesCourt = !courtOnly || listing.courtReserved;
    const matchesActive = !activeOnly || !listingDate || listingDate >= today;
    const matchesDateRange = !lastDate || (listingDate && listingDate <= lastDate);
    const matchesWeekday = weekday === "all" || (listingDate && listingDate.getDay() === Number(weekday));

    return (
      matchesType &&
      matchesCategory &&
      matchesLevel &&
      matchesKeyword &&
      matchesPrefecture &&
      matchesMunicipality &&
      matchesCourt &&
      matchesActive &&
      matchesDateRange &&
      matchesWeekday
    );
  });

  return filtered.sort((a, b) => {
    if (sort === "new") {
      return new Date(b.createdAt || 0) - new Date(a.createdAt || 0);
    }

    const dateA = parseLocalDate(a.date)?.getTime() || 0;
    const dateB = parseLocalDate(b.date)?.getTime() || 0;
    return sort === "dateDesc" ? dateB - dateA : dateA - dateB;
  });
}

function getFilteredFacilities() {
  const prefecture = elements.facilitySearchPrefecture.value;
  const municipality = elements.facilitySearchMunicipality.value;
  const reservationMethod = elements.facilitySearchReservation.value;
  const facilityType = elements.facilitySearchType.value;
  const keyword = elements.facilitySearchKeyword.value.trim().toLowerCase();

  return getAllFacilities().filter((facility) => {
    const haystack = [
      facility.name,
      facility.prefecture,
      facility.municipality,
      facility.address,
      facility.source,
      facility.reservationMethod,
      facility.facilityType,
      facility.notes,
    ]
      .join(" ")
      .toLowerCase();
    const matchesPrefecture = prefecture === "all" || facility.prefecture === prefecture;
    const matchesMunicipality =
      municipality === "all" || facility.municipality === municipality;
    const matchesReservation =
      reservationMethod === "all" || facility.reservationMethod === reservationMethod;
    const matchesType = facilityType === "all" || facility.facilityType === facilityType;
    const matchesKeyword = !keyword || haystack.includes(keyword);

    return matchesPrefecture && matchesMunicipality && matchesReservation && matchesType && matchesKeyword;
  });
}

