function startApplication(listing) {
  elements.privateNotice.textContent = "";

  if (listing.type === "opponent" && !hasRegisteredTeam()) {
    elements.applicationForm.hidden = true;
    elements.privateNotice.textContent =
      "対戦相手募集へ応募するには、先に18歳以上の代表者によるチーム登録が必要です。";
    elements.teamForm.scrollIntoView({ behavior: "smooth", block: "start" });
    return;
  }

  elements.applicationForm.hidden = false;
  elements.applicationForm.elements.listingId.value = listing.id;
  elements.applicationTarget.textContent = `応募先: ${listing.title}`;
  elements.applicationForm.elements.message.value = "";
  elements.applicationForm.scrollIntoView({ behavior: "smooth", block: "start" });
}

function renderFacilities() {
  elements.facilityList.replaceChildren();

  if (!hasFacilitySearchCriteria()) {
    renderFacilityMessage(
      "条件を入力すると施設一覧を表示します",
      "都道府県、市区町村、施設タイプ、予約方法、キーワードのいずれかを選択・入力してください。",
    );
    return;
  }

  const facilities = getFilteredFacilities();

  if (facilities.length === 0) {
    renderFacilityMessage(
      "条件に合う登録施設がありません",
      "条件を変えるか、見つけた施設を下の施設情報追加フォームから登録してください。",
    );
    return;
  }

  facilities.forEach((facility) => {
    const item = document.createElement("article");
    item.className = "facility-item";

    const top = document.createElement("div");
    top.className = "facility-top";

    const title = facility.url ? document.createElement("a") : document.createElement("strong");
    title.textContent = facility.name;
    if (facility.url) {
      title.href = facility.url;
      title.target = "_blank";
      title.rel = "noreferrer";
      title.className = "facility-title-link";
    }

    const tag = document.createElement("span");
    tag.className = "facility-tag";
    tag.textContent = facility.facilityType || "体育館";

    const reservationTag = document.createElement("span");
    reservationTag.className = "facility-tag reservation";
    reservationTag.textContent = facility.reservationMethod;

    const tagWrap = document.createElement("div");
    tagWrap.className = "facility-tags";
    tagWrap.append(tag, reservationTag);

    top.append(title, tagWrap);

    const meta = document.createElement("p");
    const address = facility.address ? ` / 所在地: ${facility.address}` : "";
    meta.textContent = `${buildArea(facility)}${address} / 情報確認日: ${
      facility.lastChecked || "未設定"
    }`;

    const notes = document.createElement("p");
    notes.textContent = facility.notes || "メモなし";

    const actions = document.createElement("div");
    actions.className = "card-actions";

    if (facility.reservationUrl || facility.url) {
      const link = document.createElement("a");
      link.href = facility.reservationUrl || facility.url;
      link.target = "_blank";
      link.rel = "noreferrer";
      link.className = "button-link";
      if (facility.officialUrl) {
        link.textContent = "公式サイトを見る";
      } else if (facility.source === "labola") {
        link.textContent = "施設ページを見る";
      } else {
        link.textContent = facility.reservationUrl ? "予約方法を見る" : "公式ページ";
      }
      actions.append(link);
    }

    const mapLink = document.createElement("a");
    const mapQuery =
      Number.isFinite(facility.lat) && Number.isFinite(facility.lon)
        ? `${facility.lat},${facility.lon}`
        : `${facility.name} ${buildArea(facility)}`;
    mapLink.href = `https://www.google.com/maps/search/?api=1&query=${encodeURIComponent(mapQuery)}`;
    mapLink.target = "_blank";
    mapLink.rel = "noreferrer";
    mapLink.className = "button-link map-link";
    mapLink.textContent = "地図を見る";
    actions.append(mapLink);

    const createListing = document.createElement("button");
    createListing.type = "button";
    createListing.className = "secondary";
    createListing.textContent = "この施設で募集";
    createListing.addEventListener("click", () => {
      prefillListingFromFacility(facility);
    });
    actions.append(createListing);

    if (facility.source !== "catalog") {
      const del = document.createElement("button");
      del.className = "danger";
      del.type = "button";
      del.textContent = "削除";
      del.addEventListener("click", () => {
        state.facilities = state.facilities.filter((item) => item.id !== facility.id);
        saveState();
        updateMunicipalitySelect();
        updateFacilitySearchMunicipalitySelect();
        render();
      });
      actions.append(del);
    }

    item.append(top, meta, notes, actions);
    elements.facilityList.append(item);
  });
}

