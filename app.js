function loadState() {
  const saved = localStorage.getItem(STORAGE_KEY);
  if (!saved) {
    return normalizeState({ listings: [], facilities: sampleState.facilities, team: null, applications: [] });
  }

  try {
    const parsed = JSON.parse(saved);
    return normalizeState({
      listings: Array.isArray(parsed.listings) ? parsed.listings : [],
      facilities: Array.isArray(parsed.facilities) ? parsed.facilities : [],
      team: parsed.team || null,
      applications: Array.isArray(parsed.applications) ? parsed.applications : [],
    });
  } catch {
    return { listings: [], facilities: [], team: null, applications: [] };
  }
}

function normalizeState(nextState) {
  return {
    ...nextState,
    listings: nextState.listings.map((listing) => {
      let normalizedListing = normalizeLocation(listing);

      if (normalizedListing.category === "U18" && normalizedListing.title?.includes("U18女子")) {
        normalizedListing = { ...normalizedListing, category: "U18女子" };
      }

      if (normalizedListing.category === "U18" && normalizedListing.title?.includes("U18男子")) {
        normalizedListing = { ...normalizedListing, category: "U18男子" };
      }

      if (normalizedListing.category === "U15" && normalizedListing.title?.includes("U15女子")) {
        normalizedListing = { ...normalizedListing, category: "U15女子" };
      }

      if (normalizedListing.category === "U15" && normalizedListing.title?.includes("U15男子")) {
        normalizedListing = { ...normalizedListing, category: "U15男子" };
      }

      return normalizedListing;
    }),
    facilities: nextState.facilities.map(normalizeLocation),
    team: nextState.team ? normalizeLocation(nextState.team) : null,
    applications: Array.isArray(nextState.applications) ? nextState.applications : [],
  };
}

function normalizeLocation(item) {
  const parsed = parseArea(item.area || "");
  const prefecture = item.prefecture || parsed.prefecture;
  const municipality = item.municipality || parsed.municipality;
  const officialUrl = item.officialUrl || facilityOfficialLinks[item.id] || "";
  const isExternalFacility = item.source === "labola";

  return {
    ...item,
    prefecture,
    municipality,
    area: buildArea({ prefecture, municipality, area: item.area }),
    facilityType: item.facilityType || "体育館",
    officialUrl,
    url: officialUrl || item.url,
    reservationUrl: isExternalFacility ? officialUrl || item.url : item.reservationUrl,
    notes: isExternalFacility ? labolaFacilityNote : item.notes,
  };
}

function parseArea(area) {
  const prefecture = prefectures.find((candidate) => area.startsWith(candidate)) || "";
  return {
    prefecture,
    municipality: prefecture ? area.replace(prefecture, "").trim() : area.trim(),
  };
}

function buildArea(item) {
  const area = `${item.prefecture || ""}${item.municipality || ""}`;
  return area || item.area || "";
}

